"""Retícula de los glifos de Contenedor.

Cada glifo se dibuja sobre la retícula de azulejos de la piscina: cinco
columnas y nueve filas. Las filas van de 6 (arriba) a -2 (abajo):

    filas 6 y 5   zona de ascendentes y mayúsculas
    filas 4 a 0   altura de x (la fila 0 apoya en la línea de base)
    filas -1 y -2 zona de descendentes

Símbolos:

    #   placa: un azulejo que el cuerpo lleva puesto
    *   pez: un azulejo desprendido (se dibuja girado 45°)
    .   azulejo vacío: la piel, o el agua que ya no está

`G(fila_superior, *filas)` escribe las filas de arriba hacia abajo desde
la fila indicada. Una fila de seis caracteres ocupa la celda entera (se usa
en la raya y en el guion bajo, para que se toquen de una celda a la otra).

Los acentos no se dibujan en la retícula: son peces sueltos, con posición
fraccionaria (columna, fila), porque flotan sobre la letra.
"""


def G(superior, *filas):
    return {superior - i: fila for i, fila in enumerate(filas)}


