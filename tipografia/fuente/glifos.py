def todos():
    """Devuelve {carácter: definición} para todo lo que se dibuja en retícula."""
    base = {}
    for tabla in (MINUSCULAS, MAYUSCULAS, CIFRAS, SIGNOS):
        base.update(tabla)
    return base


def validar():
    for ch, filas in todos().items():
        for fila, texto in filas.items():
            assert -2 <= fila <= 6, (ch, fila)
            assert len(texto) in (5, 6), (ch, fila, texto)
            assert set(texto) <= set("#*."), (ch, fila, texto)
    for ch, (base, acento) in COMPUESTOS.items():
        assert base in todos(), (ch, base)
        assert acento in ACENTOS, (ch, acento)


if __name__ == "__main__":
    validar()
    print(len(todos()), "glifos en retícula,", len(COMPUESTOS), "compuestos,",
          len(ORNAMENTOS), "ornamentos")
